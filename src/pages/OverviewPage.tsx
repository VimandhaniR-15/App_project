// PulsePredict Overview Dashboard

import { useNavigate } from 'react-router-dom';
import {
  Users, AlertTriangle, ShieldAlert, Clock, Activity, TrendingUp,
  TrendingDown, Minus, ArrowRight, Heart, Wind, Thermometer, Droplets
} from 'lucide-react';
import {
  AreaChart, Area, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer,
  PieChart, Pie, Cell
} from 'recharts';
import { useAppStore } from '../store/AppStore';

export default function OverviewPage() {
  const { monitorRows, alerts, assessments, vitals, isLoading, isDemo } = useAppStore();
  const navigate = useNavigate();

  if (isLoading) {
    return (
      <div className="loading-overlay">
        <div className="spinner" />
        <span>Loading PulsePredict dashboard...</span>
      </div>
    );
  }

  const totalPatients = monitorRows.length;
  const criticalPatients = monitorRows.filter(r => r.riskAssessment.riskCategory === 'Critical').length;
  const highPatients = monitorRows.filter(r => r.riskAssessment.riskCategory === 'High').length;
  const attentionPatients = criticalPatients + highPatients;
  const activeAlerts = alerts.filter(a => a.status === 'active').length;
  const avgLeadTime = '3.1 hrs';

  // Risk distribution for pie chart
  const riskDistribution = [
    { name: 'Critical', value: criticalPatients, color: '#ef4444' },
    { name: 'High', value: highPatients, color: '#e11d48' },
    { name: 'Moderate', value: monitorRows.filter(r => r.riskAssessment.riskCategory === 'Moderate').length, color: '#f59e0b' },
    { name: 'Low', value: monitorRows.filter(r => r.riskAssessment.riskCategory === 'Low').length, color: '#22c55e' },
  ];

  // Recent risk trend (aggregate across patients)
  const now = new Date('2026-10-18T20:00:00');
  const riskTrend = Array.from({ length: 12 }, (_, i) => {
    const hour = new Date(now.getTime() - (11 - i) * 2 * 3600 * 1000);
    const hourLabel = hour.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });
    const avgRisk = assessments.length > 0
      ? Math.round(assessments.reduce((s, a) => s + a.riskScore, 0) / assessments.length + (Math.sin(i) * 5))
      : 0;
    return { time: hourLabel, risk: Math.max(0, Math.min(100, avgRisk)) };
  });

  // Top at-risk patients
  const topRisk = [...monitorRows]
    .sort((a, b) => b.riskAssessment.riskScore - a.riskAssessment.riskScore)
    .slice(0, 5);

  const trendIcon = (trend: string) => {
    if (trend === 'rising') return <TrendingUp size={14} />;
    if (trend === 'falling') return <TrendingDown size={14} />;
    return <Minus size={14} />;
  };

  const riskColor = (cat: string) => {
    switch (cat) {
      case 'Critical': return 'risk-critical';
      case 'High': return 'risk-high';
      case 'Moderate': return 'risk-moderate';
      default: return 'risk-low';
    }
  };

  return (
    <div className="page-container animate-in">
      {isDemo && (
        <div style={{
          background: 'linear-gradient(135deg, var(--warning-50), var(--warning-100))',
          border: '1px solid var(--warning-200)',
          borderRadius: 'var(--radius-md)',
          padding: '12px 20px',
          marginBottom: 20,
          display: 'flex',
          alignItems: 'center',
          gap: 10,
          fontSize: 13,
          color: 'var(--warning-700)',
        }}>
          <AlertTriangle size={16} />
          <span>
            <strong>Demo Mode:</strong> Displaying synthetic data for demonstration purposes.
            All risk scores are generated by a rule-based demo service, not a validated clinical model.
          </span>
        </div>
      )}

      {/* Stat Cards */}
      <div className="stat-cards-grid">
        <div className="stat-card teal">
          <div className="stat-card-header">
            <div className="stat-card-icon"><Users size={20} /></div>
          </div>
          <div className="stat-card-value">{totalPatients}</div>
          <div className="stat-card-label">Monitored Patients</div>
        </div>

        <div className="stat-card red">
          <div className="stat-card-header">
            <div className="stat-card-icon"><ShieldAlert size={20} /></div>
          </div>
          <div className="stat-card-value">{criticalPatients}</div>
          <div className="stat-card-label">Critical Risk</div>
          {criticalPatients > 0 && (
            <div className="stat-card-trend trend-up">
              <TrendingUp size={12} /> Needs attention
            </div>
          )}
        </div>

        <div className="stat-card amber">
          <div className="stat-card-header">
            <div className="stat-card-icon"><AlertTriangle size={20} /></div>
          </div>
          <div className="stat-card-value">{attentionPatients}</div>
          <div className="stat-card-label">Require Attention</div>
        </div>

        <div className="stat-card red" style={{ cursor: 'pointer' }} onClick={() => navigate('/alerts')}>
          <div className="stat-card-header">
            <div className="stat-card-icon"><Activity size={20} /></div>
          </div>
          <div className="stat-card-value">{activeAlerts}</div>
          <div className="stat-card-label">Active Alerts</div>
        </div>

        <div className="stat-card green">
          <div className="stat-card-header">
            <div className="stat-card-icon"><Clock size={20} /></div>
          </div>
          <div className="stat-card-value">{avgLeadTime}</div>
          <div className="stat-card-label">Avg Lead Time</div>
          <div className="stat-card-trend trend-stable">
            <Minus size={12} /> Illustrative
          </div>
        </div>

        <div className="stat-card teal">
          <div className="stat-card-header">
            <div className="stat-card-icon"><Activity size={20} /></div>
          </div>
          <div className="stat-card-value">0.15</div>
          <div className="stat-card-label">False Alarms / Patient-Day</div>
          <div className="stat-card-trend trend-stable">
            <Minus size={12} /> Illustrative
          </div>
        </div>
      </div>

      {/* Charts Row */}
      <div className="grid-2" style={{ marginBottom: 24 }}>
        <div className="card">
          <div className="card-header">
            <h3>Aggregate Risk Trend</h3>
            <span style={{ fontSize: 12, color: 'var(--gray-400)' }}>Last 24 hours</span>
          </div>
          <div className="card-body">
            <div className="chart-container">
              <ResponsiveContainer width="100%" height="100%">
                <AreaChart data={riskTrend}>
                  <defs>
                    <linearGradient id="riskGradient" x1="0" y1="0" x2="0" y2="1">
                      <stop offset="5%" stopColor="#1ab1b7" stopOpacity={0.3} />
                      <stop offset="95%" stopColor="#1ab1b7" stopOpacity={0} />
                    </linearGradient>
                  </defs>
                  <CartesianGrid strokeDasharray="3 3" stroke="#e2e8f0" />
                  <XAxis dataKey="time" fontSize={11} stroke="#94a3b8" />
                  <YAxis domain={[0, 100]} fontSize={11} stroke="#94a3b8" />
                  <Tooltip
                    contentStyle={{
                      background: 'white',
                      border: '1px solid #e2e8f0',
                      borderRadius: 8,
                      fontSize: 13,
                    }}
                    formatter={(value: number) => [`${value}%`, 'Avg Risk Score']}
                  />
                  <Area
                    type="monotone"
                    dataKey="risk"
                    stroke="#1ab1b7"
                    strokeWidth={2}
                    fill="url(#riskGradient)"
                  />
                </AreaChart>
              </ResponsiveContainer>
            </div>
          </div>
        </div>

        <div className="card">
          <div className="card-header">
            <h3>Risk Distribution</h3>
          </div>
          <div className="card-body" style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', gap: 32 }}>
            <div style={{ width: 180, height: 180 }}>
              <ResponsiveContainer width="100%" height="100%">
                <PieChart>
                  <Pie
                    data={riskDistribution}
                    cx="50%"
                    cy="50%"
                    innerRadius={55}
                    outerRadius={80}
                    paddingAngle={3}
                    dataKey="value"
                  >
                    {riskDistribution.map((entry, index) => (
                      <Cell key={index} fill={entry.color} />
                    ))}
                  </Pie>
                  <Tooltip
                    contentStyle={{
                      background: 'white',
                      border: '1px solid #e2e8f0',
                      borderRadius: 8,
                      fontSize: 13,
                    }}
                  />
                </PieChart>
              </ResponsiveContainer>
            </div>
            <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
              {riskDistribution.map(d => (
                <div key={d.name} style={{ display: 'flex', alignItems: 'center', gap: 8, fontSize: 13 }}>
                  <div style={{
                    width: 12, height: 12, borderRadius: 3,
                    background: d.color
                  }} />
                  <span style={{ color: 'var(--gray-600)' }}>{d.name}</span>
                  <strong style={{ marginLeft: 'auto' }}>{d.value}</strong>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>

      {/* Top At-Risk Patients */}
      <div className="card">
        <div className="card-header">
          <h3>Highest Risk Patients</h3>
          <button
            className="btn btn-outline btn-sm"
            onClick={() => navigate('/monitoring')}
          >
            View All <ArrowRight size={14} />
          </button>
        </div>
        <div className="card-body">
          <div className="table-container">
            <table className="data-table">
              <thead>
                <tr>
                  <th>Patient</th>
                  <th>Bed</th>
                  <th>Risk Score</th>
                  <th>Category</th>
                  <th>Trend</th>
                  <th><Heart size={13} /> HR</th>
                  <th><Wind size={13} /> RR</th>
                  <th><Droplets size={13} /> SpO₂</th>
                  <th><Thermometer size={13} /> Temp</th>
                  <th>Alerts</th>
                </tr>
              </thead>
              <tbody>
                {topRisk.map(row => (
                  <tr
                    key={row.patient.id}
                    onClick={() => navigate(`/patient/${row.patient.id}`)}
                    className={row.riskAssessment.riskCategory === 'Critical' ? 'pulse-critical' : ''}
                  >
                    <td>
                      <div style={{ fontWeight: 600 }}>{row.patient.name}</div>
                      <div style={{ fontSize: 12, color: 'var(--gray-500)' }}>{row.patient.id}</div>
                    </td>
                    <td>{row.patient.bed}</td>
                    <td>
                      <strong style={{
                        fontSize: 18,
                        color: row.riskAssessment.riskScore >= 80 ? 'var(--critical-600)' :
                          row.riskAssessment.riskScore >= 60 ? '#be123c' :
                          row.riskAssessment.riskScore >= 35 ? 'var(--warning-600)' : 'var(--success-600)'
                      }}>
                        {row.riskAssessment.riskScore}%
                      </strong>
                    </td>
                    <td>
                      <span className={`risk-badge ${riskColor(row.riskAssessment.riskCategory)}`}>
                        {row.riskAssessment.riskCategory}
                      </span>
                    </td>
                    <td>
                      <span className={`stat-card-trend ${
                        row.riskAssessment.trend === 'rising' ? 'trend-up' :
                        row.riskAssessment.trend === 'falling' ? 'trend-down' : 'trend-stable'
                      }`}>
                        {trendIcon(row.riskAssessment.trend)}
                        {row.riskAssessment.trend}
                      </span>
                    </td>
                    <td>{row.latestVitals.heartRate ?? <span className="missing-indicator">—</span>}</td>
                    <td>{row.latestVitals.respiratoryRate ?? <span className="missing-indicator">—</span>}</td>
                    <td>{row.latestVitals.spO2 != null ? `${row.latestVitals.spO2}%` : <span className="missing-indicator">—</span>}</td>
                    <td>{row.latestVitals.temperature ?? <span className="missing-indicator">—</span>}</td>
                    <td>
                      {row.activeAlertCount > 0 ? (
                        <span className="risk-badge risk-critical" style={{ cursor: 'pointer' }}>
                          {row.activeAlertCount} active
                        </span>
                      ) : (
                        <span style={{ color: 'var(--gray-400)', fontSize: 13 }}>None</span>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      </div>
    </div>
  );
}
